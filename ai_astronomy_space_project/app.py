@app.route("/")
def index():
    sort_key = request.args.get("sort", "distance")
    if sort_key not in SORT_OPTIONS:
        sort_key = "distance"
    reverse = request.args.get("order") == "desc"

    # Copy the dicts so each request starts from clean data
    data = add_derived_values([dict(p) for p in planets])
    sorted_planets = sorted(data, key=SORT_OPTIONS[sort_key], reverse=reverse)

    return render_template(
        "index.html",
        cards=render_planet_cards(sorted_planets),
        sort_key=sort_key,
        reverse=reverse,
        options=list(SORT_OPTIONS),
        curve=make_light_curve(),
        facts=AI_FACTS,
    )


