# ---------------------------------------------------------------------------
# TASK 2 - sorting with sorted() and a lambda key.
# Each option is just a lambda stored in a dictionary.
# ---------------------------------------------------------------------------
SORT_OPTIONS = {
    "distance": lambda p: p["distance_mkm"],
    "moons":    lambda p: p["moons"],
    "name":     lambda p: p["name"],
}

AU_IN_MKM = 149.6          # 1 astronomical unit in millions of km
LIGHT_SPEED_KM_S = 299_792.458


def add_derived_values(planet_list):
    """Use numpy to add orbital period, light travel time and a log-scale bar width."""
    d = np.array([p["distance_mkm"] for p in planet_list])

    au = d / AU_IN_MKM
    period_years = au ** 1.5                                   # Kepler's third law
    light_minutes = d * 1e6 / LIGHT_SPEED_KM_S / 60            # sunlight travel time
    log_d = np.log10(d)
    bar_pct = 8 + 92 * (log_d - log_d.min()) / (log_d.max() - log_d.min())

    for i, p in enumerate(planet_list):                        # loop: attach results
        p["au"] = round(float(au[i]), 2)
        p["period_years"] = round(float(period_years[i]), 2)
        p["light_minutes"] = round(float(light_minutes[i]), 1)
        p["bar_pct"] = round(float(bar_pct[i]), 1)
    return planet_list


# ---------------------------------------------------------------------------
# TASK 3 - 'Planet Cards' layout generated by a function and a loop
# ---------------------------------------------------------------------------
def render_planet_cards(planet_list):
    """Return the HTML for every planet card, built with a for-loop."""
    cards = []
    for rank, p in enumerate(planet_list, start=1):
        shown = min(p["moons"], 12)
        extra = p["moons"] - shown
        moon_dots = '<i class="moon"></i>' * shown
        if extra > 0:
            moon_dots += f'<span class="more">+{extra}</span>'
        if p["moons"] == 0:
            moon_dots = '<span class="more">no moons</span>'

        cards.append(f"""
        <article class="card">
          <div class="card-head">
            <span class="planet" style="--c:{escape(p['color'])}"></span>
            <div>
              <h3>{escape(p['name'])}</h3>
              <p class="rank">#{rank} from the Sun in this view</p>
            </div>
          </div>

          <div class="orbit-bar" title="Distance on a log scale">
            <span style="width:{p['bar_pct']}%"></span>
          </div>

          <dl>
            <div><dt>Distance</dt><dd>{p['distance_mkm']:,} million km</dd></div>
            <div><dt>In AU</dt><dd>{p['au']}</dd></div>
            <div><dt>Year length</dt><dd>{p['period_years']} Earth years</dd></div>
            <div><dt>Sunlight takes</dt><dd>{p['light_minutes']} min</dd></div>
            <div><dt>Moons</dt><dd>{p['moons']}</dd></div>
          </dl>

          <div class="moons">{moon_dots}</div>
        </article>""")
    return Markup("".join(cards))


# ---------------------------------------------------------------------------
# TASK 4 helper - a simulated exoplanet 'transit' light curve (numpy) with a
# tiny detector: it flags points that dip well below the star's normal brightness.
# ---------------------------------------------------------------------------
def make_light_curve(width=640, height=150, n=240):
    rng = np.random.default_rng(42)
    t = np.linspace(0, 1, n)
    flux = 1 + rng.normal(0, 0.0008, n)                        # noisy star brightness
    for centre in (0.28, 0.72):                                # two planet transits
        flux[np.abs(t - centre) < 0.04] -= 0.012

    smooth = np.convolve(flux, np.ones(5) / 5, mode="same")    # moving average
    threshold = np.median(smooth) - 0.005   # flag anything ~0.5% below normal brightness
    dips = smooth < threshold

    lo, hi = flux.min(), flux.max()
    xs = t * width
    ys = height - 12 - (flux - lo) / (hi - lo) * (height - 24)
    points = " ".join(f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys))
    dip_marks = [(round(float(x), 1), round(float(y), 1))
                 for x, y, d in zip(xs, ys, dips) if d]
    return {"points": points, "dips": dip_marks, "width": width, "height": height}


